#!/usr/bin/env python3
"""Generate Wave differential-limit data from sharpa_platform 5.0.5 source."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


TABLES = (
    "THUMB_CMC_SIDE_LOOKUP_TABLE",
    "THUMB_MCP_SIDE_LOOKUP_TABLE",
    "INDEX_MCP_SIDE_LOOKUP_TABLE",
    "MIDDLE_MCP_SIDE_LOOKUP_TABLE",
    "RING_MCP_SIDE_LOOKUP_TABLE",
    "PINKY_MCP_SIDE_LOOKUP_TABLE",
)


def main() -> None:
    repository = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--platform-root", type=Path, default=repository.parent / "sharpa_platform"
    )
    args = parser.parse_args()
    source_path = (
        args.platform_root
        / "plugins/wave_control_plugin/motion/config/lookup_tables.h"
    )
    source = source_path.read_text(encoding="utf-8")
    output = [
        "// Generated by scripts/sync_wave_hand_limits.py; do not edit.",
        "// Source: sharpa_platform Wave high-level firmware (SDK 5.0.5 baseline).",
        "#pragma once",
        "",
        "#include <array>",
        "",
        "namespace sharpa::mujoco::plugins::wave_hand::detail",
        "{",
        "struct DifferentialLimitEntry { float minimum; float maximum; };",
        "using DifferentialLimitTable = std::array<DifferentialLimitEntry, 180>;",
        "",
    ]
    for table in TABLES:
        match = re.search(
            rf"{table}\s*\[[^]]+\]\s*=\s*\{{(?P<body>.*?)\n\}};",
            source,
            re.DOTALL,
        )
        if not match:
            raise ValueError(f"missing {table} in {source_path}")
        entries = re.findall(
            r"\{\s*(-?\d+(?:\.\d+)?)f\s*,\s*(-?\d+(?:\.\d+)?)f\s*\}",
            match.group("body"),
        )
        if len(entries) != 180:
            raise ValueError(f"{table} must contain 180 entries, got {len(entries)}")
        name = table.lower()
        output.append(f"inline constexpr DifferentialLimitTable {name}{{{{")
        output.extend(f"    {{{minimum}F, {maximum}F}}," for minimum, maximum in entries)
        output.extend(("}};", ""))
    output.extend(("}  // namespace sharpa::mujoco::plugins::wave_hand::detail", ""))
    destination = (
        repository / "plugins/wave_hand/src/wave_hand_limit_tables.generated.h"
    )
    destination.write_text("\n".join(output), encoding="utf-8")


if __name__ == "__main__":
    main()
